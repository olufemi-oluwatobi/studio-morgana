// Measures every font the compiler knows, in a real browser, and writes core/font-metrics.js:
// advance widths (per 1000 units of size) for the characters 32 to 255, for the regular, bold and italic cuts.
// The compiler uses them to wrap and fit text exactly.   node tools/font-metrics.cjs
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const DIR = process.env.FANCARD_FONTS || path.join(__dirname, '..', '..', 'fancard-complete', 'fancard-studio', 'fonts');
(async () => {
  const br = await chromium.launch(), p = await br.newPage(), out = {};
  for (const fam of fs.readdirSync(DIR).filter(f => fs.existsSync(path.join(DIR, f, 'files'))).sort()) {
    const files = fs.readdirSync(path.join(DIR, fam, 'files')).filter(f => f.endsWith('.woff2') && f.includes('-latin-') && !f.includes('-latin-ext-'));
    for (const [w, st] of [[400, 'normal'], [700, 'normal'], [400, 'italic'], [300, 'normal'], [500, 'normal']]) {
      const f = `${fam}-latin-${w}-${st}.woff2`; if (!files.includes(f)) continue;
      const b64 = fs.readFileSync(path.join(DIR, fam, 'files', f)).toString('base64');
      out[`${fam}/${w}/${st}`] = await p.evaluate(async ([b64, key]) => {
        const ff = new FontFace('m' + key, `url(data:font/woff2;base64,${b64})`); await ff.load(); document.fonts.add(ff);
        const c = document.createElement('canvas').getContext('2d'); c.font = `1000px m${key}`;
        return Array.from({ length: 224 }, (_, i) => Math.round(c.measureText(String.fromCharCode(32 + i)).width));
      }, [b64, Object.keys(out).length]);
    }
  }
  await br.close();
  fs.writeFileSync(path.join(__dirname, '..', 'core', 'font-metrics.js'),
    `// generated by tools/font-metrics.cjs: advance widths per 1000 units of size, characters 32 to 255. Do not edit.\nexport default ${JSON.stringify(out)};\n`);
  console.log(Object.keys(out).length, 'cuts measured');
})();
