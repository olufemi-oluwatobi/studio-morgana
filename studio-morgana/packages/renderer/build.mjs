// Builds the browser runtime for the web app:
//   apps/web/public/runtime/compiler.worker.js  the compile worker (godtongue + page build)
//   apps/web/public/runtime/vfs-base.json       fonts, styles and the engine, read by the worker's in-memory fs
//   apps/web/src/render/bridge.gen.ts           the in-frame bridge, as a string the app injects into each page
//   apps/web/src/render/engine-version.gen.ts   a hash of everything that changes pixels (part of every fingerprint)
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const GT = path.resolve(here, '..', '..', '..', 'godtongue');
const WEB = path.resolve(here, '..', '..', 'apps', 'web');
const OUT = path.join(WEB, 'public', 'runtime');
const GEN = path.join(WEB, 'src', 'render');
fs.mkdirSync(OUT, { recursive: true });
fs.mkdirSync(GEN, { recursive: true });
const kb = (p) => (fs.statSync(p).size / 1e3).toFixed(0) + ' KB';
const nm = (p) => path.join(here, 'node_modules', p);
const resolveDep = (name) => { for (const d of [nm(name), path.join(here, '..', '..', 'node_modules', name)]) if (fs.existsSync(d)) return d; throw new Error('missing dependency ' + name + ' (run npm install)'); };

// each godtongue module gets its own file:// URL, so ROOT and HERE resolve to the same paths as in vfs-base.json
const metaUrl = { name: 'meta-url', setup(b) { b.onLoad({ filter: /\.js$/ }, async (a) => {
  if (!a.path.startsWith(GT) || a.path.includes('node_modules')) return;
  const src = fs.readFileSync(a.path, 'utf8');
  return { contents: src.replaceAll('import.meta.url', JSON.stringify('file://' + a.path)), loader: 'js' };
}); } };

const shim = (f) => path.join(here, 'shims', f);
await esbuild.build({
  entryPoints: [path.join(here, 'src', 'compiler-worker.js')], bundle: true, format: 'iife', platform: 'browser',
  outfile: path.join(OUT, 'compiler.worker.js'), minify: true, logLevel: 'warning', plugins: [metaUrl],
  inject: [shim('globals.js')], nodePaths: [path.join(here, 'node_modules'), path.join(here, '..', '..', 'node_modules')],
  alias: {
    'node:fs': shim('shim-fs.js'), 'node:path': path.join(resolveDep('path-browserify'), 'index.js'), 'node:url': shim('shim-url.js'),
    'node:crypto': shim('shim-crypto.js'), 'node:child_process': shim('shim-cp.js'),
  },
});

const bridge = await esbuild.build({
  entryPoints: [path.join(here, 'src', 'bridge.js')], bundle: true, format: 'iife', platform: 'browser', write: false, minify: true, logLevel: 'warning',
  nodePaths: [path.join(here, 'node_modules'), path.join(here, '..', '..', 'node_modules')],
});
const bridgeJs = bridge.outputFiles[0].text.replaceAll('</script', '<\\/script');
fs.writeFileSync(path.join(GEN, 'bridge.gen.ts'), '// generated by packages/renderer/build.mjs\nexport const BRIDGE = ' + JSON.stringify(bridgeJs) + ';\n');

// the files the compiler and the page build read at run time
const files = {}, dirs = {};
const add = (p) => { files[p] = fs.readFileSync(p).toString('base64'); };
const listDir = (d, keep) => { const names = fs.readdirSync(d).filter(keep); dirs[d] = names; return names; };
add(path.join(GT, 'web', 'engine.js'));
const styles = path.join(GT, 'styles');
if (fs.existsSync(styles)) for (const f of listDir(styles, (f) => f.endsWith('.gt'))) add(path.join(styles, f));
const fontsDir = path.resolve(GT, '..', 'fancard-complete', 'fancard-studio', 'fonts');
if (fs.existsSync(fontsDir)) {
  for (const fam of listDir(fontsDir, (f) => fs.statSync(path.join(fontsDir, f)).isDirectory())) {
    const d = path.join(fontsDir, fam, 'files');
    if (!fs.existsSync(d)) continue;
    dirs[path.join(fontsDir, fam)] = ['files'];
    for (const f of listDir(d, (f) => f.endsWith('.woff2') && f.includes('-latin-') && !f.includes('-latin-ext-'))) add(path.join(d, f));
  }
}
fs.writeFileSync(path.join(OUT, 'vfs-base.json'), JSON.stringify({ root: GT, files, dirs }));

// the compiler for the API (no engine, no fonts): checks what the model writes before anyone renders it
{
  const styleFiles = {}, styleDirs = {};
  if (fs.existsSync(styles)) { styleDirs[styles] = fs.readdirSync(styles).filter((f) => f.endsWith('.gt')); for (const f of styleDirs[styles]) styleFiles[path.join(styles, f)] = fs.readFileSync(path.join(styles, f)).toString('base64'); }
  const API = path.resolve(here, '..', '..', 'apps', 'api', 'src', 'gt');
  fs.mkdirSync(API, { recursive: true });
  await esbuild.build({
    entryPoints: [path.join(here, 'src', 'checker.js')], bundle: true, format: 'esm', platform: 'neutral', mainFields: ['module', 'main'],
    outfile: path.join(API, 'checker.gen.js'), minify: true, logLevel: 'warning', plugins: [metaUrl],
    inject: [shim('globals.js')], nodePaths: [path.join(here, 'node_modules'), path.join(here, '..', '..', 'node_modules')],
    define: { __GT_VFS_DATA__: JSON.stringify({ root: GT, files: styleFiles, dirs: styleDirs }) },
    banner: { js: '// generated by packages/renderer/build.mjs: the godtongue compiler for the API' },
    alias: {
      'node:fs': shim('shim-fs.js'), 'node:path': path.join(resolveDep('path-browserify'), 'index.js'), 'node:url': shim('shim-url.js'),
      'node:crypto': shim('shim-crypto.js'), 'node:child_process': shim('shim-cp.js'),
    },
  });
  fs.writeFileSync(path.join(API, 'checker.gen.d.ts'), `// generated by packages/renderer/build.mjs
export interface GtDiagnostic { level: string; line?: number; col?: number; msg: string; hint?: string; range?: { line: number; col: number; len: number }; fix?: { replace: string; label: string }; follows?: number; internal?: boolean }
export interface GtElement { name: string; line: number | null; box: [number, number, number, number]; kind: string; text?: string; font?: string; size?: number; fill?: string; looks: string[] }
export interface GtChecked { ok: boolean; diagnostics: GtDiagnostic[]; elements: Record<string, GtElement>; kind: string | null; size: [number, number] | null; category: string | null }
export function check(source: string, files?: Record<string, Uint8Array>): GtChecked;
`);
  console.log('checker.gen.js', kb(path.join(API, 'checker.gen.js')));
}

// the engine version: anything that changes pixels changes this, and with it every fingerprint
const h = crypto.createHash('sha256');
for (const p of [path.join(GT, 'web', 'engine.js'), path.join(GT, 'engines', 'web.js'), path.join(here, 'src', 'bridge.js')]) h.update(fs.readFileSync(p));
for (const d of ['core', 'packs']) for (const f of fs.readdirSync(path.join(GT, d)).sort()) if (f.endsWith('.js')) h.update(fs.readFileSync(path.join(GT, d, f)));
fs.writeFileSync(path.join(GEN, 'engine-version.gen.ts'), '// generated by packages/renderer/build.mjs\nexport const ENGINE_VERSION = ' + JSON.stringify(h.digest('hex').slice(0, 16)) + ';\n');

console.log('compiler.worker.js', kb(path.join(OUT, 'compiler.worker.js')), '· vfs-base.json', kb(path.join(OUT, 'vfs-base.json')), '· bridge', (bridgeJs.length / 1e3).toFixed(0), 'KB',
  '·', Object.keys(files).length, 'runtime files');
