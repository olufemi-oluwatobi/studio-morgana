// Dockets → apps/api/src/dockets.gen.ts. Each docket's example must compile, or the build stops.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { check } from '../src/gt/checker.gen.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..', '..', 'dockets');
const out = [], bad = [];
for (const niche of fs.readdirSync(root).filter((d) => fs.statSync(path.join(root, d)).isDirectory()).sort()) {
  for (const id of fs.readdirSync(path.join(root, niche)).sort()) {
    const dir = path.join(root, niche, id);
    if (!fs.existsSync(path.join(dir, 'docket.md'))) continue;
    const md = fs.readFileSync(path.join(dir, 'docket.md'), 'utf8');
    const source = fs.existsSync(path.join(dir, 'piece.gt')) ? fs.readFileSync(path.join(dir, 'piece.gt'), 'utf8') : '';
    const head = md.split(/^## /m)[0];
    const field = (k) => (head.match(new RegExp(`^${k}:\\s*(.+)$`, 'mi')) || [])[1]?.trim() ?? '';
    const files = {};
    for (const f of fs.readdirSync(dir)) if (/\.(png|jpe?g|webp)$/i.test(f) && f !== 'render.png') files[f] = new Uint8Array(fs.readFileSync(path.join(dir, f)));
    const r = check(source, files);
    if (!source || !r.ok) bad.push(`${niche}/${id}: ${source ? r.diagnostics.filter((d) => d.level === 'error').map((d) => `line ${d.line}: ${d.msg}`).join('; ') : 'no piece.gt'}`);
    out.push({ id, niche, name: field('name') || id, kinds: field('kinds'), size: field('size'), tags: field('tags'), use: field('use when'), text: md.trim(), source });
  }
}
if (bad.length) { console.error('dockets whose example does not compile:\n  ' + bad.join('\n  ')); process.exit(1); }
fs.writeFileSync(path.resolve(here, '..', 'src', 'dockets.gen.ts'), `// generated by apps/api/scripts/build-dockets.mjs from /dockets: do not edit
export interface Docket { id: string; niche: string; name: string; kinds: string; size: string; tags: string; use: string; text: string; source: string }
export const DOCKETS: Docket[] = ${JSON.stringify(out, null, 1)};
`);
console.log('dockets.gen.ts', out.length, 'dockets');
